from wpipe_engine.core.compiler import ASTCompiler


def test_ast_compiler_generates_standard_microservice_files():
    compiler = ASTCompiler()
    canvas = {
        "nodes": [
            {"id": "n1", "data": {"node_type": "trigger", "trigger_type": "api", "label": "Start"}},
            {"id": "n2", "data": {"node_type": "step", "namespace": "wpipe_steps.connectivity", "func_name": "HttpRequest", "label": "FetchAPI"}},
            {"id": "n3", "data": {"node_type": "step", "namespace": "wpipe_steps.security", "func_name": "NmapScanStep", "label": "ScanTarget"}},
        ]
    }
    files = compiler.compile_canvas(canvas, project_name="security_scanner")

    assert "app/pipelines.py" in files
    assert "app/main.py" in files
    assert "tests/test_pipeline.py" in files
    assert "requirements.txt" in files
    assert "README.md" in files

    pipe_code = files["app/pipelines.py"]
    assert "Pipeline(pipeline_name=\"security_scanner\")" in pipe_code
    assert "HttpRequestStep as HttpRequest" in pipe_code or "HttpRequest" in pipe_code
    assert (
        'NmapScanStep(target="127.0.0.1")' in pipe_code
        or "NmapScanStep(target='127.0.0.1')" in pipe_code
    )
    assert "William Rodriguez" in files["README.md"]


def test_smart_ast_merge_preserves_custom_code():
    compiler = ASTCompiler()
    canvas = {
        "nodes": [
            {"id": "n1", "data": {"node_type": "step", "label": "MyStep"}},
        ]
    }
    existing_code = """# Generated by WPipe Studio
from wpipe import Pipeline

# >>> [WPIPE:CUSTOM_IMPORTS:START]
import numpy as np
import cv2
# <<< [WPIPE:CUSTOM_IMPORTS:END]


# >>> [WPIPE:CUSTOM_LOGIC:START]
def custom_matrix_filter(data):
    return data * 2
# <<< [WPIPE:CUSTOM_LOGIC:END]


def build_pipeline() -> Pipeline:
    pipe = Pipeline(pipeline_name="old")
    return pipe
"""

    files = compiler.compile_canvas(
        canvas, project_name="merged_pipeline", existing_pipeline_code=existing_code
    )
    new_pipe_code = files["app/pipelines.py"]

    # Verify custom imports and custom logic were NOT overwritten!
    assert "import numpy as np" in new_pipe_code
    assert "import cv2" in new_pipe_code
    assert "def custom_matrix_filter(data):" in new_pipe_code
    assert "Pipeline(pipeline_name=\"merged_pipeline\")" in new_pipe_code


def test_ai_step_generates_state_file_with_prompt_docstring():
    compiler = ASTCompiler()
    canvas = {
        "nodes": [
            {
                "id": "n1",
                "data": {
                    "node_type": "step",
                    "block_type": "wpipe_ai_step",
                    "func_name": "EntityExtractorStep",
                    "label": "EntityExtractorStep",
                    "notes": "Extraer entidades nombradas (personas, lugares, fechas) del texto recibido en el payload y agregarlas a context.data['entities']",
                },
            }
        ]
    }
    files = compiler.compile_canvas(canvas, project_name="ai_pipeline")

    assert "app/pipelines.py" in files
    assert "from states.entity_extractor_step import EntityExtractorStep" in files["app/pipelines.py"]
    assert "EntityExtractorStep()" in files["app/pipelines.py"]

    state_path = "app/states/entity_extractor_step.py"
    assert state_path in files, f"Expected {state_path} to be generated in files"
    state_code = files[state_path]

    assert "AI AGENT PROMPT & IMPLEMENTATION SPECIFICATION" in state_code
    assert "Extraer entidades nombradas" in state_code
    assert "@step" in state_code
    assert "@to_obj(PipelineContextDTO)" in state_code
    assert "class EntityExtractorStep:" in state_code


def test_ast_compiler_multi_trigger_canvas():
    """Verify that multiple triggers on the same canvas generate named Pipeline instances and endpoints."""
    compiler = ASTCompiler()
    canvas = {
        "nodes": [
            # Trigger 1: Main REST API
            {"id": "t1", "data": {"node_type": "trigger", "trigger_type": "api", "trigger_param": "/run"}},
            {"id": "s1", "data": {"node_type": "step", "namespace": "wpipe_steps.connectivity", "func_name": "HttpRequest", "label": "FetchAPI"}},
            # Trigger 2: Cron schedule
            {"id": "t2", "data": {"node_type": "trigger", "trigger_type": "cron", "trigger_param": "0 * * * *"}},
            {"id": "s2", "data": {"node_type": "step", "namespace": "wpipe_steps.security", "func_name": "NmapScanStep", "label": "ScanTarget"}},
        ],
        "edges": [
            {"source": "t1", "target": "s1"},
            {"source": "t2", "target": "s2"},
        ]
    }
    files = compiler.compile_canvas(canvas, project_name="multi_service")

    pipe_code = files["app/pipelines.py"]
    assert "pipe_main: Pipeline = Pipeline(pipeline_name=\"multi_service\")" in pipe_code
    assert "pipe_cron: Pipeline = Pipeline(pipeline_name=\"multi_service_cron\")" in pipe_code
    assert '"main": pipe_main' in pipe_code
    assert '"cron": pipe_cron' in pipe_code
    assert "def build_pipeline" in pipe_code
    assert "def execute_pipeline(" in pipe_code
    assert 'pipeline_name: str = "main"' in pipe_code

    # Verify steps were partitioned correctly to their respective trigger trees
    assert "pipe_main.set_steps" in pipe_code
    assert "pipe_cron.set_steps" in pipe_code

    main_py_code = files["app/main.py"]
    assert "@app.post(\"/run\"" in main_py_code
    assert "build_pipeline(pipeline_name)" in main_py_code


def test_ast_compiler_modular_pipeline_file():
    """Verify that compiling a modular pipeline (e.g., auth) produces its dedicated module file."""
    compiler = ASTCompiler()
    canvas = {
        "nodes": [
            {"id": "t1", "data": {"node_type": "trigger", "trigger_type": "api", "trigger_param": "/auth"}},
            {"id": "s1", "data": {"node_type": "step", "label": "CustomAuthStep"}},
        ]
    }
    files = compiler.compile_canvas(canvas, project_name="auth")

    assert "app/pipelines.py" in files
    assert "app/auth.py" in files
    assert "Pipeline(pipeline_name=\"auth\")" in files["app/auth.py"]

