import { CanvasIR } from "./ir/schemas";

export interface GeneratedFile {
  path: string;
  content: string;
}

/**
 * Generate a complete production-grade Python microservice from Canvas IR.
 * Works 100% in-browser offline or as instant fallback when local engine is unavailable.
 */
export function generateMicroserviceFiles(
  canvasIr: CanvasIR,
  projectName: string = "main_pipeline",
  dockerImage: string = "python:3.11-slim"
): GeneratedFile[] {
  const nodes = canvasIr.nodes || [];
  const triggerNode = nodes.find((n) => n.data?.node_type === "trigger");
  const stepNodes = nodes.filter((n) => n.data?.node_type !== "trigger" && n.data?.node_type !== "response");

  const imports = new Set<string>([
    "from wpipe import Pipeline, step, Condition, For, Parallel, Background",
  ]);

  const stepCallList: string[] = [];

  for (const node of stepNodes) {
    const data = node.data || ({} as any);
    const ntype = data.node_type;
    const label = data.label || "CustomStep";
    const ns = data.namespace || "";

    if (ns && ns.startsWith("wpipe_steps")) {
      const stepClass = label.endsWith("Step") ? label : `${label}Step`;
      imports.add(`from ${ns} import ${stepClass} as ${label}`);
      stepCallList.push(`        ${label}()`);
    } else if ((ntype as string) === "ai_step" || data.origin === "described") {
      stepCallList.push(`        # AI Step: ${label}\n        ${label}()`);
    } else if ((ntype as string) === "custom_step" || ntype === "step") {
      stepCallList.push(`        ${label}()`);
    } else if (ntype === "condition") {
      const expr = data.condition_expression || "is_valid == True";
      stepCallList.push(`        Condition(expression="${expr}", branch_true=[])`);
    } else if (ntype === "for") {
      const iters = data.for_iterations || 5;
      stepCallList.push(`        For(iterations=${iters}, steps=[])`);
    } else if (ntype === "while") {
      const expr = data.condition_expression || "retry_count < 3";
      stepCallList.push(`        For(validation_expression="${expr}", steps=[])`);
    } else if (ntype === "parallel") {
      const merge = data.merge_policy || "accumulate";
      stepCallList.push(`        Parallel(steps=[], merge_policy="${merge}")`);
    } else if (ntype === "background") {
      stepCallList.push(`        Background(step=${label}())`);
    } else {
      stepCallList.push(`        ${label}()`);
    }
  }

  const stepsCode = stepCallList.length > 0 ? stepCallList.join(",\n") : "        # Empty pipeline";
  const importsCode = Array.from(imports).sort().join("\n");

  const pipelinePy = `# Generated by WPipe Studio
${importsCode}

# >>> [WPIPE:CUSTOM_IMPORTS:START]
# Add custom imports or dependencies here
# <<< [WPIPE:CUSTOM_IMPORTS:END]


# >>> [WPIPE:CUSTOM_LOGIC:START]
# Add custom helper functions, step transforms, or middleware here
@step
def default_logging_step(context: dict) -> dict:
    context["execution_timestamp"] = "simulated"
    return context
# <<< [WPIPE:CUSTOM_LOGIC:END]


def build_pipeline() -> Pipeline:
    pipe = Pipeline(pipeline_name="${projectName}")
    pipe.set_steps([
${stepsCode}
    ])
    return pipe


if __name__ == "__main__":
    pipe = build_pipeline()
    result = pipe.run({"test_mode": True})
    print("Pipeline execution result:", result)
`;

  const triggerType = triggerNode?.data?.trigger_type || "api";
  const triggerParam = triggerNode?.data?.trigger_param || "/run";

  const mainPy = `# Microservice Entrypoint for ${projectName}
import uvicorn
from fastapi import FastAPI, HTTPException
from app.pipelines import build_pipeline

app = FastAPI(
    title="${projectName}",
    description="WPipe Microservice generated by WPipe Studio",
    version="1.0.0",
)


@app.get("/health")
def health():
    return {"status": "healthy", "service": "${projectName}", "trigger": "${triggerType}"}


@app.post("${triggerParam.startsWith("/") ? triggerParam : `/${triggerParam}`}")
def run_pipeline(payload: dict | None = None):
    try:
        pipe = build_pipeline()
        return pipe.run(payload or {})
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))


if __name__ == "__main__":
    uvicorn.run("app.main:app", host="0.0.0.0", port=8000, reload=True)
`;

  const dockerfile = `FROM ${dockerImage}

WORKDIR /app

RUN apt-get update && apt-get install -y --no-install-recommends curl && rm -rf /var/lib/apt/lists/*

COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

COPY . .

EXPOSE 8000

CMD ["uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "8000"]
`;

  const dockerCompose = `services:
  ${projectName}:
    build: .
    ports:
      - "8000:8000"
    environment:
      - PYTHONUNBUFFERED=1
      - SERVICE_NAME=${projectName}
    restart: unless-stopped
`;

  const requirementsTxt = `wpipe>=2.5.13
wpipe-steps>=1.0.2
fastapi>=0.110.0
uvicorn>=0.28.0
pytest>=8.0.0
pytest-cov>=4.1.0
pydantic>=2.0.0
`;

  const makefile = `.PHONY: run test docker-build docker-run

run:
	python app/main.py

test:
	pytest tests/ -v --cov=app

docker-build:
	docker build -t ${projectName}:latest .

docker-run:
	docker run -p 8000:8000 ${projectName}:latest
`;

  const testPipelinePy = `# Unit Tests for ${projectName}
import sys
import pathlib
import pytest

sys.path.insert(0, str(pathlib.Path(__file__).parent.parent))

from app.pipelines import build_pipeline


def test_pipeline_instantiation():
    """Validates that the WPipe Pipeline object instantiates correctly."""
    pipe = build_pipeline()
    assert pipe is not None
    assert bool(getattr(pipe, "pipeline_name", None) or getattr(pipe, "name", None))


def test_pipeline_dry_run():
    """Runs a dry-run execution with simulated payload."""
    pipe = build_pipeline()
    try:
        res = pipe.run({"test_mode": True})
        assert res is not None
    except Exception as exc:
        # Non-fatal during mock runs if network steps aren't configured
        assert str(exc) != ""
`;

  const readmeMd = `# ${projectName}

Microservicio generado automáticamente por **WPipe Studio (wisrovi SUITE)**.

## Tecnologías y Librerías Relevantes
- **WPipe** (\`>=2.5.13\`): Motor de orquestación de pipelines síncronos y asíncronos.
- **FastAPI**: Framework web REST asíncrono para el punto de entrada (\`${triggerParam}\`).
- **Uvicorn**: Servidor ASGI de producción.
- **Pydantic**: Validación y tipado de contratos DTO.
- **Pytest**: Suite de pruebas unitarias (\`tests/test_pipeline.py\`).
- **Docker**: Contenedorización de microservicios con base \`${dockerImage}\`.

## Ejecución Local
\`\`\`bash
python -m venv .venv
source .venv/bin/activate
pip install -r requirements.txt
python app/main.py
\`\`\`

## Tests
\`\`\`bash
pytest tests/ -v
\`\`\`
`;

  const runTestsDocker = `#!/usr/bin/env bash
set -e
docker run --rm -v "$(pwd):/app" -w /app ${dockerImage} bash -c "pip install -r requirements.txt && pytest tests/ -v"
`;

  return [
    { path: "app/__init__.py", content: "# Package marker\n" },
    { path: "app/pipelines.py", content: pipelinePy },
    { path: "app/main.py", content: mainPy },
    { path: "Dockerfile", content: dockerfile },
    { path: "docker-compose.yml", content: dockerCompose },
    { path: "requirements.txt", content: requirementsTxt },
    { path: "Makefile", content: makefile },
    { path: "tests/test_pipeline.py", content: testPipelinePy },
    { path: "README.md", content: readmeMd },
    { path: "run_tests_docker.sh", content: runTestsDocker },
  ];
}
