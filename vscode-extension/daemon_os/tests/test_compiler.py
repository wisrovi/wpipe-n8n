from wpipe_engine.core.compiler import ASTCompiler


def test_ast_compiler_generates_standard_microservice_files():
    compiler = ASTCompiler()
    canvas = {
        "nodes": [
            {"id": "n1", "data": {"node_type": "trigger", "trigger_type": "api", "label": "Start"}},
            {"id": "n2", "data": {"node_type": "step", "namespace": "wpipe_steps.connectivity", "func_name": "HttpRequest", "label": "FetchAPI"}},
            {"id": "n3", "data": {"node_type": "step", "namespace": "wpipe_steps.security", "func_name": "NmapScanStep", "label": "ScanTarget"}},
        ]
    }
    files = compiler.compile_canvas(canvas, project_name="security_scanner")

    assert "app/pipelines.py" in files
    assert "app/main.py" in files
    assert "tests/test_pipeline.py" in files
    assert "requirements.txt" in files
    assert "README.md" in files

    pipe_code = files["app/pipelines.py"]
    assert "Pipeline(pipeline_name=\"security_scanner\")" in pipe_code
    assert "HttpRequestStep as HttpRequest" in pipe_code or "HttpRequest" in pipe_code
    assert (
        'NmapScanStep(target="127.0.0.1")' in pipe_code
        or "NmapScanStep(target='127.0.0.1')" in pipe_code
    )
    assert "William Rodriguez" in files["README.md"]


def test_smart_ast_merge_preserves_custom_code():
    compiler = ASTCompiler()
    canvas = {
        "nodes": [
            {"id": "n1", "data": {"node_type": "step", "label": "MyStep"}},
        ]
    }
    existing_code = """# Generated by WPipe Studio
from wpipe import Pipeline

# >>> [WPIPE:CUSTOM_IMPORTS:START]
import numpy as np
import cv2
# <<< [WPIPE:CUSTOM_IMPORTS:END]


# >>> [WPIPE:CUSTOM_LOGIC:START]
def custom_matrix_filter(data):
    return data * 2
# <<< [WPIPE:CUSTOM_LOGIC:END]


def build_pipeline() -> Pipeline:
    pipe = Pipeline(pipeline_name="old")
    return pipe
"""

    files = compiler.compile_canvas(
        canvas, project_name="merged_pipeline", existing_pipeline_code=existing_code
    )
    new_pipe_code = files["app/pipelines.py"]

    # Verify custom imports and custom logic were NOT overwritten!
    assert "import numpy as np" in new_pipe_code
    assert "import cv2" in new_pipe_code
    assert "def custom_matrix_filter(data):" in new_pipe_code
    assert "Pipeline(pipeline_name=\"merged_pipeline\")" in new_pipe_code
